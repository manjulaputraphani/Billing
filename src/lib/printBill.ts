import type { SaleBillDetail } from "../db/billing";
import type { ShopDetails } from "../db/settings";
import { splitGst } from "../logic/gst";
import { formatQuantity, formatRupees, type Unit } from "../logic/units";

function escapeHtml(value: string): string {
  return value.replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c] ?? c,
  );
}

/** Print the GST bill through a hidden iframe (also offers "Save as PDF"). */
export function printBill(bill: SaleBillDetail, shop: ShopDetails): void {
  const { cgstPaise, sgstPaise } = splitGst(bill.gstPaise);
  const rows = bill.lines
    .map(
      (line) =>
        `<tr><td>${escapeHtml(line.itemName)}</td><td class="r">${formatQuantity(
          line.qtyBase,
          line.unit as Unit,
        )}</td><td class="r">${formatRupees(line.unitPricePaise)}</td><td class="r">${formatRupees(
          line.lineTotalPaise,
        )}</td></tr>`,
    )
    .join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(
    bill.billNo,
  )}</title><style>
    body{font-family:-apple-system,Segoe UI,sans-serif;color:#111;margin:32px;font-size:13px}
    h1{font-size:20px;margin:0 0 2px} h2{font-size:13px;letter-spacing:.12em;text-transform:uppercase;margin:18px 0 8px}
    .muted{color:#555;margin:1px 0} table{width:100%;border-collapse:collapse;margin-top:8px}
    th,td{border-bottom:1px solid #ddd;padding:6px 4px;text-align:left} .r{text-align:right}
    .totals{margin-top:10px;margin-left:auto;width:52%} .totals div{display:flex;justify-content:space-between;padding:2px 0}
    .grand{font-weight:700;border-top:1px solid #111;margin-top:4px;padding-top:4px}
    .foot{margin-top:18px;color:#555;font-size:11px}
    .cancelled{color:#b91c1c;font-weight:700;letter-spacing:.08em}
  </style></head><body>
    <h1>${escapeHtml(shop.name || "My Shop")}</h1>
    <p class="muted">${escapeHtml(shop.address || "")}</p>
    <p class="muted">${shop.phone ? `Phone: ${escapeHtml(shop.phone)}` : ""}${
      shop.gstin ? ` · GSTIN: ${escapeHtml(shop.gstin)}` : ""
    }</p>
    <h2>Tax Invoice${bill.cancelled ? ' <span class="cancelled">· CANCELLED</span>' : ""}</h2>
    <p class="muted">Bill No: <b>${escapeHtml(bill.billNo)}</b> · Date: ${bill.saleDate}</p>
    <p class="muted">Customer: ${escapeHtml(bill.customerName || "Walk-in")}${
      bill.customerPhone ? ` · ${escapeHtml(bill.customerPhone)}` : ""
    }</p>
    <table><thead><tr><th>Item</th><th class="r">Qty</th><th class="r">Rate</th><th class="r">Amount</th></tr></thead>
    <tbody>${rows}</tbody></table>
    <div class="totals">
      <div><span>Subtotal</span><span>${formatRupees(bill.subtotalPaise)}</span></div>
      ${
        bill.discountPaise > 0
          ? `<div><span>Discount</span><span>−${formatRupees(bill.discountPaise)}</span></div>`
          : ""
      }
      ${
        bill.gstPaise > 0
          ? `<div><span>CGST</span><span>${formatRupees(cgstPaise)}</span></div>
             <div><span>SGST</span><span>${formatRupees(sgstPaise)}</span></div>`
          : ""
      }
      <div class="grand"><span>Total</span><span>${formatRupees(bill.totalPaise)}</span></div>
      <div><span>Paid (${bill.paymentMode})</span><span>${formatRupees(bill.paidPaise)}</span></div>
      <div><span>Balance</span><span>${formatRupees(bill.totalPaise - bill.paidPaise)}</span></div>
    </div>
    <p class="foot">Thank you! · Generated by Stock Tracker</p>
  </body></html>`;

  const frame = document.createElement("iframe");
  frame.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0";
  document.body.appendChild(frame);
  const doc = frame.contentWindow?.document;
  if (!doc) return;
  doc.open();
  doc.write(html);
  doc.close();
  const fire = () => {
    try {
      frame.contentWindow?.focus();
      frame.contentWindow?.print();
    } catch {
      // printing must never crash the screen
    }
  };
  setTimeout(fire, 300);
  setTimeout(() => frame.remove(), 2000);
}
